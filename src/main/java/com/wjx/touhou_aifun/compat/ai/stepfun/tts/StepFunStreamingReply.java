package com.wjx.touhou_aifun.compat.ai.stepfun.tts;

import com.github.tartaricacid.touhoulittlemaid.ai.manager.entity.TTSCallback;
import com.github.tartaricacid.touhoulittlemaid.ai.service.tts.TTSConfig;
import com.github.tartaricacid.touhoulittlemaid.entity.passive.EntityMaid;
import com.wjx.touhou_aifun.TouhouAIFun;
import com.wjx.touhou_aifun.chat.ChatFlowManager;
import org.apache.commons.lang3.StringUtils;
import org.jetbrains.annotations.Nullable;

import java.net.http.HttpRequest;
import java.util.function.Consumer;

/**
 * Incremental StepFun synthesis for one reply that is still being generated by the LLM.
 *
 * <p>Instead of one HTTP request per sentence (which loses the session-wide delivery context), all
 * sentences of the reply are fed into a single official WebSocket session as soon as they are
 * complete. The provider cuts and synthesizes them sentence by sentence, and the first audible chunk
 * is played while the model is still writing.</p>
 *
 * <p>Failures before the first PCM chunk are retried once over the ordinary HTTP endpoint with the
 * complete reply text; failures after playback started only end the stream, so speech is never
 * played twice.</p>
 */
public final class StepFunStreamingReply {
    private final StepFunTTSClient client;
    private final TTSConfig config;
    private final TTSCallback callback;
    private final EntityMaid maid;
    private final int generation;
    private final Consumer<byte[]> audioSink;
    private final Object lock = new Object();

    private StepFunTTSStream stream;
    private boolean finished;
    private boolean failedBeforeAudio;
    private boolean fallbackStarted;
    private String fullText = StringUtils.EMPTY;

    public StepFunStreamingReply(StepFunTTSClient client, TTSConfig config, TTSCallback callback,
                                 int generation, Consumer<byte[]> audioSink) {
        this.client = client;
        this.config = config;
        this.callback = callback;
        this.maid = callback.getMaid();
        this.generation = generation;
        this.audioSink = audioSink;
    }

    /** Feeds one complete sentence; the first call also opens the WebSocket session. */
    public void speak(String sentence) {
        if (sentence == null || sentence.isBlank()) {
            return;
        }
        synchronized (this.lock) {
            if (this.finished || this.failedBeforeAudio) {
                return;
            }
            if (this.stream == null) {
                try {
                    this.stream = this.client.openStream(this.maid, this.generation, this.config, sentence,
                            this.callback, this::onStreamFinished);
                    this.stream.start();
                } catch (RuntimeException error) {
                    // A construction/handshake failure is handled like any other pre-audio failure:
                    // the reply is retried once over HTTP when it finishes.
                    TouhouAIFun.LOGGER.warn("StepFun streaming reply could not start ({}), retrying over HTTP",
                            describe(error));
                    this.failedBeforeAudio = true;
                    return;
                }
            }
            this.stream.feed(sentence);
        }
    }

    /** Marks the end of the reply and lets the provider flush the remaining audio. */
    public void finish(String fullTtsText) {
        StepFunTTSStream current;
        boolean fallbackNow;
        synchronized (this.lock) {
            if (this.finished) {
                return;
            }
            this.finished = true;
            this.fullText = StringUtils.defaultString(fullTtsText);
            current = this.stream;
            fallbackNow = this.failedBeforeAudio || current == null;
        }
        if (current != null) {
            current.finishText();
        }
        if (fallbackNow) {
            startHttpFallback();
        }
    }

    /** Abandons the session without retrying (the reply lost the right to speak). */
    public void abort() {
        StepFunTTSStream current;
        synchronized (this.lock) {
            this.finished = true;
            current = this.stream;
        }
        if (current != null) {
            current.abort();
        }
    }

    private void onStreamFinished(StepFunTTSStream.Outcome outcome, boolean anyAudio, @Nullable Throwable error) {
        if (outcome == StepFunTTSStream.Outcome.ABORTED) {
            return;
        }
        if (anyAudio) {
            // Audio is already playing on the client; a retry would duplicate the speech.
            return;
        }
        if (error != null) {
            TouhouAIFun.LOGGER.warn("StepFun streaming reply failed ({}), retrying over HTTP", describe(error));
        }
        boolean fallbackNow;
        synchronized (this.lock) {
            this.failedBeforeAudio = true;
            fallbackNow = this.finished;
        }
        if (fallbackNow) {
            startHttpFallback();
        }
    }

    private void startHttpFallback() {
        String text;
        synchronized (this.lock) {
            if (this.fallbackStarted) {
                return;
            }
            text = this.fullText;
            if (text.isBlank()) {
                return;
            }
            this.fallbackStarted = true;
        }
        if (ChatFlowManager.ttsGeneration(this.maid.getUUID()) != this.generation) {
            return;
        }
        this.client.playHttpOnly(text, this.config, new TTSCallback(this.maid, StringUtils.EMPTY, -1) {
            @Override
            public void onSuccess(byte[] data) {
                if (ChatFlowManager.ttsGeneration(maid.getUUID()) == generation) {
                    audioSink.accept(data);
                }
            }

            @Override
            public void onFailure(HttpRequest request, Throwable throwable, int errorCode) {
                TouhouAIFun.LOGGER.error("StepFun HTTP fallback for streaming reply failed: {}",
                        describe(throwable));
            }
        });
    }

    private static String describe(@Nullable Throwable throwable) {
        if (throwable == null) {
            return "unknown";
        }
        String message = throwable.getMessage();
        return message == null || message.isBlank() ? throwable.getClass().getSimpleName() : message;
    }
}
